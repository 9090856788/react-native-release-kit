import path from 'node:path';
import type { ReleaseKitConfig } from '../config/schema.js';
import type { ProjectDetectionResult } from '../detector/types.js';
import { resolveGradleTask } from '../adapters/android.js';

export interface FastlaneGenerationResult {
  relativePath: string;
  filePath: string;
  content: string;
}

export interface GenerateFastlaneOptions {
  cwd?: string;
  project?: ProjectDetectionResult;
}

export function generateAndroidAppfile(config: ReleaseKitConfig): string {
  const saPathEnv = config.signing.android.serviceAccountPathEnvName;
  const pkgName = config.android.applicationId;
  const pkgFallback = pkgName ? `"${pkgName}"` : 'ENV["ANDROID_PACKAGE_NAME"]';

  return `# Fastlane Appfile — Generated by react-native-release-kit
# Credentials are read strictly from environment variables (zero secret commits)

json_key_file(ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"]) if ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"]
package_name(ENV["ANDROID_PACKAGE_NAME"] || ${pkgFallback})
`;
}

export function generateAndroidFastfile(config: ReleaseKitConfig): string {
  const packagePath = config.android.packagePath || 'android';
  const appModule = config.android.appModule || 'app';
  const artifact = config.android.buildArtifact || 'aab';
  const flavor = config.android.flavor;
  const releaseStatus = config.android.releaseStatus || 'draft';
  const saPathEnv = config.signing.android.serviceAccountPathEnvName;

  const gradleTask = resolveGradleTask({
    variant: 'release',
    artifact,
    appModule,
    flavor,
  }).replace(/^:/, '');

  const uploadParam =
    artifact === 'aab' ? `aab: ENV["ANDROID_ARTIFACT_PATH"]` : `apk: ENV["ANDROID_ARTIFACT_PATH"]`;

  return `# Fastlane Fastfile — Generated by react-native-release-kit
default_platform(:android)

platform :android do
  desc "Build Android release ${artifact.toUpperCase()} artifact"
  lane :build_release do
    gradle(
      task: "${gradleTask}",
      project_dir: "${packagePath}/"
    )
  end

  desc "Publish validated artifact to Google Play Internal testing track"
  lane :deploy_internal do
    upload_to_play_store(
      track: "internal",
      release_status: ENV["PLAY_RELEASE_STATUS"] || "${releaseStatus}",
      json_key: ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"],
      ${uploadParam},
      skip_upload_metadata: true,
      skip_upload_images: true,
      skip_upload_screenshots: true
    )
  end

  desc "Publish validated artifact to Google Play Closed testing track"
  lane :deploy_closed do
    upload_to_play_store(
      track: ENV["PLAY_CLOSED_TRACK_NAME"] || "alpha",
      release_status: ENV["PLAY_RELEASE_STATUS"] || "${releaseStatus}",
      json_key: ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"],
      ${uploadParam},
      skip_upload_metadata: true,
      skip_upload_images: true,
      skip_upload_screenshots: true
    )
  end

  desc "Publish validated artifact to Google Play Production track"
  lane :deploy_production do
    unless ENV["ALLOW_PRODUCTION_RELEASE"] == "true"
      UI.user_error!("Production release blocked. Set ALLOW_PRODUCTION_RELEASE=true to authorize production rollout.")
    end

    upload_to_play_store(
      track: "production",
      release_status: ENV["PLAY_RELEASE_STATUS"] || "${releaseStatus}",
      json_key: ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"],
      ${uploadParam},
      skip_upload_metadata: true,
      skip_upload_images: true,
      skip_upload_screenshots: true
    )
  end
end
`;
}

export function generateIOSAppfile(config: ReleaseKitConfig): string {
  const bundleId = config.ios.bundleId;
  const bundleFallback = bundleId ? `"${bundleId}"` : 'ENV["IOS_BUNDLE_IDENTIFIER"]';

  return `# Fastlane Appfile (iOS) — Generated by react-native-release-kit
# Credentials are read strictly from environment variables (zero secret commits)

app_identifier(ENV["IOS_BUNDLE_IDENTIFIER"] || ${bundleFallback})
apple_id(ENV["APPLE_ID"]) if ENV["APPLE_ID"]
itc_team_id(ENV["ITC_TEAM_ID"]) if ENV["ITC_TEAM_ID"]
team_id(ENV["TEAM_ID"]) if ENV["TEAM_ID"]
`;
}

export function resolveFastlaneIOSSettings(
  config: ReleaseKitConfig,
  project?: ProjectDetectionResult,
): {
  packagePath: string;
  scheme: string;
  workspace: string;
  exportMethod: string;
} {
  const packagePath = config.ios.packagePath || project?.ios.packagePath || 'ios';
  const nonTestSchemes = (project?.ios.schemes || []).filter((s) => !/(?:Tests|UITests)$/i.test(s));
  const detectedScheme = nonTestSchemes[0] || project?.ios.schemes[0];
  const scheme =
    config.ios.scheme && (detectedScheme ? config.ios.scheme !== config.projectName : true)
      ? config.ios.scheme
      : detectedScheme || config.ios.scheme || config.projectName || 'App';

  const workspacePath = config.ios.workspace
    ? config.ios.workspace.includes('/')
      ? config.ios.workspace
      : `${packagePath}/${config.ios.workspace}`
    : project?.ios.workspace;

  const workspace = workspacePath || `${packagePath}/${scheme}.xcworkspace`;
  const exportMethod = config.ios.exportMethod || 'app-store';

  return { packagePath, scheme, workspace, exportMethod };
}

export function generateIOSFastfile(
  config: ReleaseKitConfig,
  project?: ProjectDetectionResult,
): string {
  const { scheme, workspace, exportMethod } = resolveFastlaneIOSSettings(config, project);
  const keyContentSecret = config.signing.ios.appStoreConnectKeyContentSecretName;
  const keyIdSecret = config.signing.ios.appStoreConnectKeyIdSecretName;
  const issuerIdSecret = config.signing.ios.appStoreConnectIssuerIdSecretName;

  return `# Fastlane Fastfile — Generated by react-native-release-kit
default_platform(:ios)

platform :ios do
  desc "Build iOS release IPA"
  lane :build_release do
    build_app(
      workspace: ENV["IOS_WORKSPACE"] || "${workspace}",
      scheme: ENV["IOS_SCHEME"] || "${scheme}",
      export_method: "${exportMethod}"
    )
  end

  desc "Build and upload to Apple TestFlight"
  lane :deploy_testflight do
    if ENV["${keyContentSecret}"] && ENV["${keyIdSecret}"] && ENV["${issuerIdSecret}"]
      app_store_connect_api_key(
        key_id: ENV["${keyIdSecret}"],
        issuer_id: ENV["${issuerIdSecret}"],
        key_content: ENV["${keyContentSecret}"],
        is_key_content_base64: true,
        in_house: false
      )
    end

    build_app(
      workspace: ENV["IOS_WORKSPACE"] || "${workspace}",
      scheme: ENV["IOS_SCHEME"] || "${scheme}",
      export_method: "${exportMethod}"
    )

    upload_to_testflight(
      skip_waiting_for_build_processing: true
    )
  end
end
`;
}

export function generateUnifiedAppfile(config: ReleaseKitConfig): string {
  const saPathEnv = config.signing.android.serviceAccountPathEnvName;
  const pkgName = config.android.applicationId;
  const pkgFallback = pkgName ? `"${pkgName}"` : 'ENV["ANDROID_PACKAGE_NAME"]';
  const bundleId = config.ios.bundleId;
  const bundleFallback = bundleId ? `"${bundleId}"` : 'ENV["IOS_BUNDLE_IDENTIFIER"]';

  return `# Fastlane Appfile — Generated by react-native-release-kit
# Credentials are read strictly from environment variables (zero secret commits)

# Android configuration
json_key_file(ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"]) if ENV["${saPathEnv}"] || ENV["SUPPLY_JSON_KEY"]
package_name(ENV["ANDROID_PACKAGE_NAME"] || ${pkgFallback})

# iOS configuration
app_identifier(ENV["IOS_BUNDLE_IDENTIFIER"] || ${bundleFallback})
apple_id(ENV["APPLE_ID"]) if ENV["APPLE_ID"]
itc_team_id(ENV["ITC_TEAM_ID"]) if ENV["ITC_TEAM_ID"]
team_id(ENV["TEAM_ID"]) if ENV["TEAM_ID"]
`;
}

export function generateUnifiedFastfile(
  config: ReleaseKitConfig,
  project?: ProjectDetectionResult,
): string {
  const androidSection = generateAndroidFastfile(config)
    .replace(/^default_platform\(:android\)\n+/, '')
    .trim();
  const iosSection = generateIOSFastfile(config, project)
    .replace(/^default_platform\(:ios\)\n+/, '')
    .trim();

  return `# Fastlane Fastfile — Generated by react-native-release-kit
default_platform(:android)

${androidSection}

${iosSection}
`;
}

export function generateGemfile(): string {
  return `# Gemfile — Generated by react-native-release-kit
# Defines Fastlane dependency for reproducible builds and CI Bundler caching

source 'https://rubygems.org'

gem 'fastlane'
`;
}

export async function generateFastlaneFiles(
  config: ReleaseKitConfig,
  options: GenerateFastlaneOptions = {},
): Promise<FastlaneGenerationResult[]> {
  const cwd = options.cwd ?? process.cwd();
  const project = options.project;
  const results: FastlaneGenerationResult[] = [];
  const appfileRel = 'fastlane/Appfile';
  const fastfileRel = 'fastlane/Fastfile';

  const hasAndroid = config.android.enabled;
  const hasIOS = config.ios.enabled;

  if (hasAndroid || hasIOS) {
    results.push({
      relativePath: 'Gemfile',
      filePath: path.resolve(cwd, 'Gemfile'),
      content: generateGemfile(),
    });
  }

  if (hasAndroid && hasIOS) {
    results.push({
      relativePath: appfileRel,
      filePath: path.resolve(cwd, appfileRel),
      content: generateUnifiedAppfile(config),
    });
    results.push({
      relativePath: fastfileRel,
      filePath: path.resolve(cwd, fastfileRel),
      content: generateUnifiedFastfile(config, project),
    });
  } else if (hasAndroid) {
    results.push({
      relativePath: appfileRel,
      filePath: path.resolve(cwd, appfileRel),
      content: generateAndroidAppfile(config),
    });
    results.push({
      relativePath: fastfileRel,
      filePath: path.resolve(cwd, fastfileRel),
      content: generateAndroidFastfile(config),
    });
  } else if (hasIOS) {
    results.push({
      relativePath: appfileRel,
      filePath: path.resolve(cwd, appfileRel),
      content: generateIOSAppfile(config),
    });
    results.push({
      relativePath: fastfileRel,
      filePath: path.resolve(cwd, fastfileRel),
      content: generateIOSFastfile(config, project),
    });
  }

  return results;
}
